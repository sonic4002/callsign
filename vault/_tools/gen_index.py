#!/usr/bin/env python3
"""Write 00-Meta/Index.md: one line per note with its type and description.

    python3 vault/_tools/gen_index.py          rewrite the index
    python3 vault/_tools/gen_index.py --check  exit 1 when the index on disk is stale

The index is generated: never edit it by hand.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vaultlib as v

INDEX = os.path.join(v.ROOT, "00-Meta", "Index.md")


def build():
    by_folder = {}
    latest = "2026-11-27"
    for path in v.notes():
        if os.path.abspath(path) == INDEX:
            continue
        fm, _, _, _ = v.read(path)
        folder = os.path.dirname(os.path.relpath(path, v.ROOT)) or "(vault root)"
        by_folder.setdefault(folder, []).append((v.name(path), fm.get("type", "?"), fm.get("description", "")))
        latest = max(latest, str(fm.get("updated", "")))
    total = sum(len(rows) for rows in by_folder.values())
    out = [
        "---",
        "title: Index",
        'description: "Generated table of every note in the vault with its type and one-line description; start navigation here."',
        "type: meta",
        "status: current",
        "tags:",
        "  - type/meta",
        "  - status/current",
        "  - agent/CLD",
        "  - origin/mixed",
        "  - area/meta",
        "created: 2026-11-27",
        f"updated: {latest}",
        "agent: CLD",
        "origin: mixed",
        "confidence: high",
        "related:",
        '  - "[[Home]]"',
        '  - "[[Conventions]]"',
        '  - "[[Agent Handoff]]"',
        "paths: []",
        "---",
        "",
        "# Index",
        "",
        f"Generated by `_tools/gen_index.py`: {total} notes. Do not edit by hand; run the script after adding a note or changing a description.",
        "",
    ]
    for folder in sorted(by_folder):
        out += [f"## {folder}", "", "| Note | Type | Description |", "|---|---|---|"]
        for stem, kind, desc in sorted(by_folder[folder]):
            out.append(f"| [[{stem}]] | {kind} | {desc.replace('|', '/')} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        on_disk = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if on_disk != text:
            print("00-Meta/Index.md is stale: run python3 vault/_tools/gen_index.py", file=sys.stderr)
            sys.exit(1)
        sys.exit(0)
    os.makedirs(os.path.dirname(INDEX), exist_ok=True)
    with open(INDEX, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(INDEX, v.ROOT))
